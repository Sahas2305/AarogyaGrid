def seed_appointments(patients: list, doctors: list):
    print("\n📅 Seeding appointments...")
    slots  = ["09:00", "10:00", "11:00", "12:00", "14:00", "15:00", "16:00"]
    statuses = ["Confirmed", "Completed", "Completed", "Cancelled", "Pending"]
    reasons = [
        "Chest pain and shortness of breath",
        "Severe migraine and photophobia",
        "Routine annual checkup",
        "Follow-up for hypertension management",
        "Knee pain and limited range of motion",
        "Persistent dry cough and fatigue",
        "Abdominal pain and bloating",
        "Skin rash and itching",
        "Child vaccination and growth assessment",
        "Back pain post-injury",
        "Dizziness and palpitations",
        "Sore throat and fever for 3 days",
        "Diabetic review and HbA1c check",
        "Shoulder stiffness after accident",
        "Acid reflux and epigastric pain",
    ]
    rows = []
    for i, pat in enumerate(patients):
        doc = doctors[i % len(doctors)]
        rows.append({
            "patient_id":       pat["patient_id"],
            "doctor_id":        doc["doctor_id"],
            "department_id":    doc["department_id"],
            "appointment_date": past_date(30 - i * 2),
            "appointment_time": slots[i % len(slots)] + ":00",
            "status":           statuses[i % len(statuses)],
            "reason":           reasons[i % len(reasons)],
        })
        # Each patient also gets a future appointment
        doc2 = doctors[(i + 3) % len(doctors)]
        rows.append({
            "patient_id":       pat["patient_id"],
            "doctor_id":        doc2["doctor_id"],
            "department_id":    doc2["department_id"],
            "appointment_date": future_date(7 + i * 3),
            "appointment_time": slots[(i + 2) % len(slots)] + ":00",
            "status":           "Pending",
            "reason":           reasons[(i + 5) % len(reasons)],
        })

    upsert("appointment", rows)
    result = supabase.table("appointment").select("appointment_id, patient_id, doctor_id, status").execute()
    print(f"  ✅ {len(result.data)} appointments in DB")
    return result.data


