# ─────────────────────────────────────────────────────────────────────────────
def hash_pw(plain: str) -> str:
    return bcrypt.hashpw(plain.encode(), bcrypt.gensalt()).decode()

def past_date(days_ago: int) -> str:
    return (date.today() - timedelta(days=days_ago)).isoformat()

def future_date(days_ahead: int) -> str:
    return (date.today() + timedelta(days=days_ahead)).isoformat()

def upsert(table: str, rows: list, conflict_col: str = None):
    """Insert rows, skipping those that already exist on conflict_col."""
    if not rows:
        return []
    try:
        result = supabase.table(table).insert(rows).execute()
        return result.data
    except Exception as e:
        print(f"  ⚠  Insert into '{table}' partially failed (likely duplicates): {e}")
        return []


